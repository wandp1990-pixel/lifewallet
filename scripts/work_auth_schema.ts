// Generate a reviewed, idempotent schema using a temporary DB, never the production DB.
import { mkdtemp, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { randomBytes } from 'node:crypto'

async function main() {
  const directory = await mkdtemp(join(tmpdir(), 'lifewallet-auth-schema-'))
  process.env.TURSO_DATABASE_URL = `file:${join(directory, 'auth.db')}`
  delete process.env.TURSO_AUTH_TOKEN
  process.env.WORK_MCP_ORIGIN = 'https://example.com'
  process.env.WORK_AUTH_SECRET = randomBytes(32).toString('hex')
  process.env.WORK_MCP_ALLOWED_EMAIL = 'owner@example.com'
  process.env.GOOGLE_CLIENT_ID = 'test-client'
  process.env.GOOGLE_CLIENT_SECRET = 'test-secret'
  try {
    const { createWorkAuth } = await import('../lib/work-auth')
    const { getMigrations } = await import('better-auth/db/migration')
    const auth = createWorkAuth()
    const plan = await getMigrations(auth.options)
    if (plan.toBeAdded.length || plan.unsafeChanges.length || plan.schemaProblems.length) throw new Error('Unexpected migration plan')
    const sql = (await plan.compileMigrations()).replace(/create table /gi, 'create table if not exists ').replace(/create unique index /gi, 'create unique index if not exists ').replace(/create index /gi, 'create index if not exists ')
    await writeFile(join(process.cwd(), 'lib/work-auth-schema.ts'), `// Generated by scripts/work_auth_schema.ts for Better Auth 1.7.7.\nexport const workAuthSchema = ${JSON.stringify(sql)}\n`)
    console.log('Auth schema generated from a temporary database')
  } finally { await rm(directory, { recursive: true, force: true }) }
}
main().catch(() => { console.error('Auth schema generation failed'); process.exitCode = 1 })
